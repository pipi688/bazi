const questions = ref<Question[]>([])
const currentQuestion = ref(0)
const answers = reactive<Record<string, string | string[]>>({})

const totalQuestions = computed(() => questions.value.length)
const progressPct = computed(() => {
  if (totalQuestions.value === 0) return '0'
  return ((currentQuestion.value + 1) / totalQuestions.value * 100).toFixed(0)
})

function hasNoneSelected(shishenKey: string): boolean {
  const arr = (answers[shishenKey] as string[]) || []
  return arr.some(v => v.startsWith('无明显'))
}

function startTest() {
  questions.value = buildQuestions()
  currentQuestion.value = 0
  Object.keys(answers).forEach(k => delete answers[k])
  stage.value = 'question'
  window.scrollTo(0, 0)
}

function restartTest() {
  questions.value = buildQuestions()
  currentQuestion.value = 0
  Object.keys(answers).forEach(k => delete answers[k])
  stage.value = 'welcome'
  window.scrollTo(0, 0)
}

function selectRadio(qId: string, value: string) {
  answers[qId] = value
}

function selectCheckbox(qId: string, value: string) {
  let arr = (answers[qId] as string[]) || []
  if (!Array.isArray(answers[qId])) arr = []
  const idx = arr.indexOf(value)

  if (idx >= 0) {
    arr.splice(idx, 1)
  } else {
    if (value.startsWith('无明显')) {
      arr = [value]
    } else {
      const noneLabels = ['无明显被冲', '无明显被合', '无明显被刑', '无明显被害', '无明显被合绊']
      noneLabels.forEach(noneVal => {
        const i = arr.indexOf(noneVal)
        if (i >= 0) arr.splice(i, 1)
      })
      arr.push(value)
    }
  }
  answers[qId] = [...arr]
}

function isSelected(qId: string, value: string): boolean {
  const sel = answers[qId]
  if (!sel) return false
  if (Array.isArray(sel)) return sel.includes(value)
  return sel === value
}

// 动态获取天干选项
function getTianganOptions(): string[] {
  const wx = answers['wuxing'] as string
  return TIANGAN_MAP[wx] || []
}

function validateCurrent(): boolean {
  const q = questions.value[currentQuestion.value]
  if (!q) return false
  if (q.type === 'radio') {
    if (!answers[q.id]) { alert('请先选择一个选项'); return false }
  } else if (q.type === 'checkbox') {
    const arr = (answers[q.id] as string[]) || []
    if (arr.length === 0) { alert('请至少选择一个选项'); return false }
  }
  return true
}

function nextQuestion() {
  if (!validateCurrent()) return
  if (currentQuestion.value < totalQuestions.value - 1) {
    currentQuestion.value++
    // 如果是依赖题且选择了"无明显"，跳过
    const q = questions.value[currentQuestion.value]
    if (q.dependsOn && hasNoneSelected(q.dependsOn)) {
      if (currentQuestion.value < totalQuestions.value - 1) {
        currentQuestion.value++
        window.scrollTo(0, 0)
        return
      } else {
        showResult()
        return
      }
    }
    window.scrollTo(0, 0)
  } else {
    showResult()
  }
}

function prevQuestion() {
  if (currentQuestion.value > 0) {
    currentQuestion.value--
    window.scrollTo(0, 0)
  }
}

// ========== 获取交互作用分析文本 ==========
function getInteractionAnalysis(label: string, shishenArr: string[], xijiVal: string): string {
  if (!xijiVal || shishenArr.length === 0) return ''
  const bodyStr = (answers['bodyStrength'] as string) || ''
  const results: string[] = []
  shishenArr.forEach(shishen => {
    const key = bodyStr + '_' + xijiVal + '_' + shishen + '_' + label
    const text = INTERACTION_ANALYSIS[key]
    if (text) results.push(shishen + '（' + xijiVal + '）：' + text)
  })
  return results.length > 0 ? results.join('<br><br>') : ''
}

